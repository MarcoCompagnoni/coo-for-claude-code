"""Builds the «What's running» section of the desk from the board: one line per project and who it waits for.

The desk is organised by action and weight, not by project. The per-project view lives in this section, at
the bottom of the desk, and the CEO does not need to read it to act. Regenerate it at every desk update.

Usage:
    python scripts/board_status.py           prints the section
    python scripts/board_status.py --desk    writes it into the desk, replacing the existing one (the last section)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_board import cells_of, load_config, table_rows  # noqa: E402

CUT = re.compile(r"\s*(?:\.\s+)?(?:Done\b|· msg )")
PREFIX = re.compile(r"^(?:(?:waiting session|waiting ceo|nothing in flight)\s*(?:\([^)]*\))?\s*[:·,]?\s*)+", re.I)
CEO_ITEM = re.compile(r"waiting ceo\s*[:(]?\s*([A-Z]{1,2}[RY]\d+|[^·;)]{1,40})", re.I)
WAITS_FOR = (("waiting session", "the session"), ("waiting ceo", "you"), ("nothing in flight", "nobody"))


def shorten(text: str, cap: int = 170) -> str:
    """Cuts a text at a whole word, with an ellipsis.

    Args:
        text: the text.
        cap: the maximum length.

    Returns:
        The text, shortened if needed.
    """
    if len(text) <= cap:
        return text
    return text[:cap].rsplit(" ", 1)[0] + "…"


def line_of(cells: list[str]) -> str:
    """Turns a board row into a line of the section.

    Args:
        cells: the four cells of a board row.

    Returns:
        A markdown table row: project, what is running, who it waits for.
    """
    name, status = cells[0], cells[3]
    who = next((w for key, w in WAITS_FOR if key in status.lower()), "?")
    if who == "you":
        match = CEO_ITEM.search(status)
        if match:
            who = "you (" + match.group(1).strip() + ")"
    state = PREFIX.sub("", CUT.split(status, 1)[0]).strip(" ·;.")
    return f"| {name} | {shorten(state) or '—'} | {who} |"


def section(board: Path) -> str:
    """Builds the section from the board.

    Args:
        board: path of BOARD.md.

    Returns:
        The markdown of the section.
    """
    text = board.read_text(encoding="utf-8")
    body = [line_of(cells_of(r)) for _, r in table_rows(text) if r and len(cells_of(r)) == 4]
    return (
        "## What's running\n\n*From the board, generated by `scripts/board_status.py`: no need to read it to act.*\n\n"
        "| Project | What's running | Waiting for |\n|---|---|---|\n" + "\n".join(body) + "\n"
    )


def into_desk(board: Path, desk: Path) -> None:
    """Replaces the last section of the desk with a fresh one.

    Args:
        board: path of BOARD.md.
        desk: path of CEO_DESK.md.
    """
    text = desk.read_text(encoding="utf-8")
    where = text.find("## What's running")
    top = text[:where] if where >= 0 else text.rstrip("\n") + "\n\n---\n\n"
    desk.write_text(top + section(board), encoding="utf-8")


if __name__ == "__main__":
    config = load_config()
    board_path = Path(config.get("board", "coo/BOARD.md"))
    if "--desk" in sys.argv:
        into_desk(board_path, Path(config.get("desk", "coo/CEO_DESK.md")))
        print("What's running written into the desk")
    else:
        print(section(board_path))
